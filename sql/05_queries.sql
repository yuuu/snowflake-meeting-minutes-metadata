-- 動作確認・活用のためのクエリ集。必要なものを個別に実行する
USE ROLE ACCOUNTADMIN;
USE SCHEMA MEETING_DB.APP;
USE WAREHOUSE MEETING_WH;

-- ===== 取り込み・実行状況 =====
SELECT SYSTEM$PIPE_STATUS('MEETING_DB.APP.TRANSCRIPT_PIPE');

SELECT FILE_PATH, LENGTH(CONTENT) LEN, LOADED_AT FROM RAW_TRANSCRIPTS ORDER BY FILE_PATH;

SELECT FILE_NAME, STATUS, ROW_COUNT, FIRST_ERROR_MESSAGE, LAST_LOAD_TIME
FROM TABLE(INFORMATION_SCHEMA.COPY_HISTORY(TABLE_NAME => 'RAW_TRANSCRIPTS', START_TIME => DATEADD(hour, -1, CURRENT_TIMESTAMP())))
ORDER BY FILE_NAME;

SELECT NAME, STATE, ERROR_MESSAGE, SCHEDULED_TIME, COMPLETED_TIME
FROM TABLE(MEETING_DB.INFORMATION_SCHEMA.TASK_HISTORY(TASK_NAME => 'ANALYZE_TRANSCRIPTS_TASK'))
ORDER BY SCHEDULED_TIME DESC LIMIT 10;

-- ===== 解析結果 =====
SELECT FILE_PATH, PROJECT_CODE, PROJECT_RAW, STATUS_CODE, SUMMARY FROM TRANSCRIPT_METADATA ORDER BY FILE_PATH;

SELECT FILE_PATH, LISTAGG(TAG_CODE, ', ') WITHIN GROUP (ORDER BY TAG_CODE) TAGS
FROM TRANSCRIPT_TAG GROUP BY 1 ORDER BY 1;

SELECT FILE_PATH, TAG_RAW FROM UNKNOWN_TAG_CANDIDATE ORDER BY 1, 2;

-- 根拠の文が原文に存在するか
SELECT m.FILE_PATH, e.value::STRING AS EVIDENCE, CONTAINS(r.CONTENT, e.value::STRING) AS FOUND
FROM TRANSCRIPT_METADATA m
JOIN (SELECT FILE_PATH, ANY_VALUE(CONTENT) CONTENT FROM RAW_TRANSCRIPTS GROUP BY 1) r USING (FILE_PATH),
LATERAL FLATTEN(input => m.EVIDENCE) e
ORDER BY 1;

-- ===== 活用例 =====
-- Snowflakeが話題に出た会議のうち、ブロック中のもの
SELECT m.FILE_PATH, m.SUMMARY
FROM TRANSCRIPT_METADATA m
JOIN TRANSCRIPT_TAG t USING (FILE_PATH)
WHERE t.TAG_CODE = 'snowflake' AND m.STATUS_CODE = 'BLOCKED';

-- プロジェクト別の状況
SELECT p.PROJECT_NAME, m.STATUS_CODE, COUNT(*) N
FROM TRANSCRIPT_METADATA m LEFT JOIN PROJECT_MASTER p USING (PROJECT_CODE)
GROUP BY 1, 2 ORDER BY 1;

