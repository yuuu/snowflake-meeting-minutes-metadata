USE ROLE ACCOUNTADMIN;
USE SCHEMA MEETING_DB.APP;

-- CREATE OR REPLACE で作り直すと外部IDが変わる。
-- 作り直す場合は STORAGE_AWS_EXTERNAL_ID = '<控えておいた外部ID>' を追加すると元の外部IDを維持できる
CREATE OR REPLACE STORAGE INTEGRATION MEETING_S3_INT
  TYPE = EXTERNAL_STAGE
  STORAGE_PROVIDER = 'S3'
  ENABLED = TRUE
  STORAGE_AWS_ROLE_ARN = '${ROLE_ARN}'
  STORAGE_ALLOWED_LOCATIONS = ('s3://${BUCKET}/transcripts/');

DESC INTEGRATION MEETING_S3_INT;
